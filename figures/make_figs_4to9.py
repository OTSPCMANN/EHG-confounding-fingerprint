    # ---- D3 基线参考线 + 文字标签 ----
    ax.axvline(0.532, color=C_D3, ls=":", lw=1.8, zorder=1)   # 改 0.532 可平移此线
    # ax.text(0.532, -0.96, ...): 位置参数同上; 这里 y=-0.96 比 chance 标签更低, 以错开避免重叠
    ax.text(0.538, -0.5, "D3 baseline (0.532)", color=C_D3, fontsize=FS_ANNOT,
            ha="left", va="top",
            bbox=dict(boxstyle="round,pad=0.15", fc="white", ec="none", alpha=0.1))

