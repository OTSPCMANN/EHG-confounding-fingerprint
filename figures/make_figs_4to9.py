FPR_GRID = np.linspace(0, 1, 1001)
FIG4_NPZ = os.path.join(FIGDIR, "fig4_roc_data.npz")
FIG4_CSV = os.path.join(FIGDIR, "fig4_roc_data.csv")


def _interp_tpr(fpr, tpr):
    order = np.argsort(fpr)
    return np.interp(FPR_GRID, fpr[order], tpr[order], left=0.0, right=1.0)


def _envelope(curves):
    arr = np.vstack(curves)
    return arr.mean(axis=0), np.percentile(arr, 2.5, axis=0), np.percentile(arr, 97.5, axis=0)


def fig4_roc_build():
    """重算 Figure 4 的 ROC 画图数据并落盘 (npz 供画图 + csv 供查看/手绘)。

    只在原始预测结果变化时需要运行 (较慢: 含 10x5 折重建与 2000 次母亲级
    cluster bootstrap)。日常修改图样式只需重跑 fig4_roc() 读取缓存即可。
    """
    import pipe05_ci as P
    from run_experiment import load_data
    from sklearn.metrics import roc_curve, roc_auc_score

    # ---- (a) development OOF ----
    p = np.load(os.path.join(EXPD, "pipeline_oof_rebuilt.npz"), allow_pickle=True)
    y_db = p["y"].astype(int)
    oof = p["oof"].astype(float)                       # (10, 300)
    tpr_a = []
    for s in range(oof.shape[0]):
        f, t, _ = roc_curve(y_db, oof[s])
        tpr_a.append(_interp_tpr(f, t))
    mean_a, lo_a, hi_a = _envelope(tpr_a)
    auc_a = [roc_auc_score(y_db, oof[s]) for s in range(oof.shape[0])]
    assert len(auc_a) == 10, len(auc_a)
    print("[fig4a] mean per-seed OOF AUC = %.4f (expect 0.5928)" % np.mean(auc_a))

    # ---- (b) external validation (DS) ----
    db, ds, ALL_COLS = load_data()
    yds = ds.label.values.astype(int)
    dirs = sorted(glob.glob(os.path.join(EXPD, "P1CI_P6eff050_seed*_20260903_*")))
    assert dirs, "no P1CI_P6eff050_seed* dirs found"
    per_seed_roc, auc_b, fold_preds = [], [], []
    for d in dirs:
        res = P.rebuild_run(d, db, ds, ALL_COLS)
        if not res["passed"]:
            raise RuntimeError("rebuild 断言未通过 seed=%s" % res["seed"])
        fts, fas, fps = [], [], []
        for fd in res["folds"]:
            if fd["p_ds"] is None:
                continue
            f, t, _ = roc_curve(yds, fd["p_ds"])
            fts.append(_interp_tpr(f, t))
            fas.append(float(roc_auc_score(yds, fd["p_ds"])))
            fps.append(fd["p_ds"])
        per_seed_roc.append(np.mean(np.vstack(fts), axis=0))
        auc_b.append(float(np.mean(fas)))
        fold_preds.append(fps)
    per_seed_roc = np.array(per_seed_roc)
    per_fold = np.array(fold_preds)                    # (10, 5, 26)
    mean_b, _, _ = _envelope(per_seed_roc)
    assert len(auc_b) == 10, len(auc_b)
    print("[fig4b] mean per-seed DS AUC = %.4f (expect 0.5788)" % np.mean(auc_b))

    # ---- 母亲级 cluster bootstrap 逐点包络 (18 母亲 / 26 记录) ----
    mm = pd.read_csv(os.path.join(BASE, "results", "checkpoints_lit_features_v2", "tpehgt_ds_mother_map.csv"))
    mothers = mm["mother_id"].values
    uniq_m = np.unique(mothers)
    m2r = {m: np.where(mothers == m)[0] for m in uniq_m}
    rng = np.random.RandomState(44)
    boot, n_degen = [], 0
    for _ in range(2000):
        sel = rng.choice(uniq_m, size=len(uniq_m), replace=True)
        idx = np.concatenate([m2r[m] for m in sel])
        if len(np.unique(yds[idx])) < 2:
            n_degen += 1
            continue
        stack = []
        for s in range(per_fold.shape[0]):
            for k in range(per_fold.shape[1]):
                f, t = roc_curve(yds[idx], per_fold[s, k][idx])[:2]
                stack.append(_interp_tpr(f, t))
        boot.append(np.mean(np.vstack(stack), axis=0))
    boot = np.array(boot)
    lo_b = np.percentile(boot, 2.5, axis=0)
    hi_b = np.percentile(boot, 97.5, axis=0)
    print("[fig4b] cluster bootstrap band built (degen=%d)" % n_degen)

    # ---- 落盘: npz (画图用) + csv (查看/手绘用) ----
    np.savez(FIG4_NPZ, fpr=FPR_GRID,
             dev_mean=mean_a, dev_lo=lo_a, dev_hi=hi_a, auc_a=np.asarray(auc_a),
             ds_mean=mean_b, ds_lo=lo_b, ds_hi=hi_b, auc_b=np.asarray(auc_b),
             n_degen=n_degen)
    pd.DataFrame({"fpr": FPR_GRID,
                  "dev_mean": mean_a, "dev_lo": lo_a, "dev_hi": hi_a,
                  "ds_mean": mean_b, "ds_lo": lo_b, "ds_hi": hi_b}
                 ).to_csv(FIG4_CSV, index=False, encoding="utf-8-sig")
    print("[fig4] data ->", FIG4_NPZ)
    print("[fig4] data ->", FIG4_CSV)
    return FIG4_NPZ


