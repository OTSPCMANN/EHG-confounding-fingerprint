    _lab_w_px = max(t.get_window_extent().width for t in ax.get_yticklabels())  # 最宽标签宽度(像素)
    ax.tick_params(axis="y", pad=_lab_w_px * 72.0 / fig.dpi / 2.0 + 6.0)       # pad: 刻度标签距轴框的偏移(pt)
    ax.set_xlabel("Record-level out-of-fold AUC\n(mean \u00b1 1 SD across 10 seeds)",
                  fontsize=FS_LABEL)                                 # x 轴标题字号
    ax.set_ylabel("Preterm contrast", fontsize=FS_LABEL)            # y 轴标题字号
    _finish(ax, grid_axis="x", close_frame=True)                    # forest 图用 x 向网格 + 闭合四轴

    out = os.path.join(FIGOUT, "fig9_1010.png")
    _save(fig, out)
    _save_b64(out)
    _close(fig)
    return out


