def _seed_metric(cfg):
    """experiments/<cfg>_seed*/pipe_03_sfs_*.xlsx -> {seed: parsed}; 同种子取最新 stamp。"""
    import _summarize_runs as S
    out = {}
    for d in glob.glob(os.path.join(EXPD, cfg + "_seed*")):
        fps = glob.glob(os.path.join(d, "pipe_03_sfs_*.xlsx"))
        if not fps:
            continue
        p = S.parse(fps[0])
        if p is None:
            continue
        parts = os.path.basename(d).split("_seed")[1].split("_")
        seed = int(parts[0])
        stamp = "_".join(parts[1:]) if len(parts) > 1 else ""
        if seed not in out or stamp > out[seed][0]:
            out[seed] = (stamp, p)
    return {k: v[1] for k, v in out.items()}


def _seed_vals(cfg, metric, seeds=SEEDS):
    rows = _seed_metric(cfg)
    return np.array([rows[s][metric] for s in seeds if s in rows], float)


def _finish(ax, *, ylabel=None, ylim=None, yticks=None, title=None,
            grid_axis="y", close_frame=True):
    """统一的坐标轴收尾: 面板标题 / 轴标题 / 网格 / 闭合四轴。"""
    if title:
        ax.set_title(title, fontsize=FS_PANEL, loc="left", pad=8)   # 面板标题: 左对齐, pad=与轴框间距(pt)
    if ylabel:
        ax.set_ylabel(ylabel, fontsize=FS_LABEL)                    # y 轴标题字号
    if ylim:
        ax.set_ylim(*ylim)                                          # y 轴取值范围
    if yticks is not None:
        ax.set_yticks(yticks)                                       # 显式指定 y 刻度位置
    if grid_axis:
        ax.grid(axis=grid_axis, color=C_GRID, linewidth=0.7, zorder=0)  # 点状网格: 颜色/线宽; zorder=0 压在数据下
    ax.tick_params(axis="both", which="major", labelsize=FS_TICK)   # 刻度标签字号
    if close_frame:
        ax.spines["top"].set_visible(True)                          # 显示上轴框(四边闭合)
        ax.spines["right"].set_visible(True)                        # 显示右轴框(四边闭合)
        ax.tick_params(top=False, right=False, labeltop=False, labelright=False)  # 上/右仅留框线, 不画刻度与标签


def _dot_whisker(ax, x, vals, color, rng, *, main=False,
                 jitter=0.16, dot_ms=11.0, seed_ms=16.0):
    """种子散点 + 均值点 + ±1 SD 端帽须 (Fig 6 / 7 / 8 共用)。

    参数
    ----
    ax      : 目标坐标轴 (Axes)。
    x       : 该组数据的横坐标位置 (类别序号, 如 0/1/2/3)。
    vals    : 该组的种子级数值数组 (如 10 个 seed 的 AUC); 均值/±1 SD 由它算出。
    color   : 该组统一配色 (散点 / 须 / 均值点同色)。
    rng     : numpy 随机数生成器, 固定种子保证散点抖动位置可复现。
    main    : True=主配置组, 均值点加黑色描边以突出 (默认 False 无描边)。
    jitter  : 种子散点横向抖动的总宽度 (点 x 在 x±jitter/2 内随机散布, 避免重叠)。
    dot_ms  : 均值点直径 markersize。
    seed_ms : 单个种子散点的面积 s (非直径; 面积 = 直径^2)。
    """
    vals = np.asarray(vals, float)
    m, s = float(vals.mean()), float(vals.std())
    # 种子散点: x 位置=组中心 x 叠加 ±jitter/2 抖动; s=点面积(seed_ms), alpha=透明度, edgecolor/linewidth=白描边, zorder=2 数据点层
    ax.scatter(x + (rng.random(len(vals)) - 0.5) * jitter, vals, s=seed_ms,
               color=color, alpha=SEED_ALPHA, edgecolor="white",
               linewidth=0.5, zorder=2)
    # ±1 SD 竖须: 从 m-s 到 m+s (linewidth=须线宽), zorder=3 置于散点之上
    ax.vlines(x, m - s, m + s, color=color, linewidth=3.0, zorder=3)
    # 须两端水平端帽: 以 x 为中心 ±0.06 宽 (linewidth=端帽线宽), zorder=3
    ax.hlines([m - s, m + s], x - 0.06, x + 0.06, color=color,
              linewidth=2.4, zorder=3)
    # 均值点: markersize=点直径(dot_ms); main=True 时加黑描边(markeredgecolor/width); zorder=4 最上层
    ax.plot(x, m, marker="o", markersize=dot_ms, color=color,alpha=0.8,
            markeredgecolor="black" if main else "none",
            markeredgewidth=1.3, zorder=4)
    return m, s


def _chance_hline(ax, tx, ty, ha="left"):
    # chance=0.50 参考线: 灰色虚线(linestyle="--"), linewidth=线宽, zorder=1 位于曲线之下
    ax.axhline(0.50, color=C_CHANCE, linestyle="--", linewidth=1.1, zorder=1)
    # 参考线文字标注: 位置 (tx, ty) —— tx=锚点 x, ty=锚点 y (调用处传入, 改之可移动标签);
    # fontsize=注释字号, ha/va=相对锚点的水平/垂直对齐
    ax.text(tx, ty, "chance = 0.50", color=C_CHANCE, fontsize=FS_ANNOT,
            ha=ha, va="top")


def _forest_row(ax, y, arr, color, rng, *, value_text=True,
                dim=False, x_text=None):
    """forest 行: 水平 ±1 SD 须(端帽竖直) + 均值点 + 种子散点 + 数值标注。"""
    arr = np.asarray(arr, float)
    m, s = float(arr.mean()), float(arr.std())
    # 水平 ±1 SD 须 (lw=须线宽, zorder=3) + 两端竖直端帽 (vlines 用 y±0.10 做出端帽)
    ax.hlines(y, m - s, m + s, color=color, lw=2.6, zorder=3)
    ax.vlines([m - s, m + s], y - 0.10, y + 0.10, color=color, lw=2.6, zorder=3)
    # 均值点: markersize=点直径, 黑描边; dim=True(非临床参考行)时整点半透明(alpha=0.6)
    ax.plot(m, y, "o", markersize=17, color=color, markeredgecolor="black",
            markeredgewidth=1.5, zorder=5, alpha=0.6 if dim else 1.0)
    # 种子散点: 纵向抖动(±0.17), s=点面积, alpha=透明度, 白描边; zorder=4
    ax.scatter(arr, y + (rng.random(len(arr)) - 0.5) * 0.34, s=70,
               color=color, alpha=SEED_ALPHA, edgecolor="white",
               linewidth=0.4, zorder=4)
    if value_text:
        # 右侧数值标注: 位置 (x_text, y) —— x_text=锚点横坐标(调用处传入, 改之左右移), y=行序号;
        # ha="right" 右对齐到 x_text, va="center" 垂直居中, fontsize=刻度字号, fontweight="bold" 加粗
        ax.text(x_text, y, "%.3f  \u00b1  %.3f" % (m, s), color=color,
                fontsize=FS_TICK, ha="right", va="center", fontweight="bold")
    return m, s


def _tight_bbox(fig):
    """内容(文字/图形)外边界 + 固定留白: 宽 +PAD_W_MM、高 +PAD_H_MM (两侧均分)。"""
    fig.canvas.draw()
    tb = fig.get_tightbbox()
    px = (PAD_W_MM * MM) / 2.0
    py = (PAD_H_MM * MM) / 2.0
    return Bbox.from_bounds(tb.x0 - px, tb.y0 - py, tb.width + 2 * px, tb.height + 2 * py)


def _save(fig, path):
    fig.savefig(path, dpi=DPI, bbox_inches=_tight_bbox(fig))
    print("[save]", path)


