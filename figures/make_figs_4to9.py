def _fig_single(left_mm=M_LEFT, right_mm=M_RIGHT, top_mm=M_TOP, bottom_mm=M_BOTTOM):
    """单面板画布: 绘图框固定 AX_W_MM x AX_H_MM。"""
    # 画布尺寸 = 左边距 + 绘图框 + 右边距 (边距只决定画布, 不改绘图框大小)
    W = left_mm + AX_W_MM + right_mm
    H = bottom_mm + AX_H_MM + top_mm
    fig = plt.figure(figsize=(W * MM, H * MM), dpi=DPI)   # figsize 单位英寸, mm 由 MM 换算
    # add_axes 用"画布占比"定位 (左, 底, 宽, 高): 使轴框恒为 AX_W_MM x AX_H_MM
    ax = fig.add_axes([left_mm / W, bottom_mm / H, AX_W_MM / W, AX_H_MM / H])
    return fig, ax


def _fig_stacked(left_mm=M_LEFT, right_mm=M_RIGHT, top_mm=M_TOP,
                 bottom_mm=M_BOTTOM, hgap_mm=M_HGAP):
    """两面板竖排画布: 每格绘图框各为 AX_W_MM x AX_H_MM; 返回 (fig, (top, bottom))。"""
    # 高度 = 底边距 + 下轴框 + 面板间距 + 上轴框 + 顶边距
    W = left_mm + AX_W_MM + right_mm
    H = bottom_mm + AX_H_MM + hgap_mm + AX_H_MM + top_mm
    fig = plt.figure(figsize=(W * MM, H * MM), dpi=DPI)   # figsize 单位英寸
    # 下/上两个轴框, 各自锁定为 AX_W_MM x AX_H_MM (hgap_mm 为两者间距)
    ax_bot = fig.add_axes([left_mm / W, bottom_mm / H, AX_W_MM / W, AX_H_MM / H])
    ax_top = fig.add_axes([left_mm / W, (bottom_mm + AX_H_MM + hgap_mm) / H,
                           AX_W_MM / W, AX_H_MM / H])
    return fig, (ax_top, ax_bot)


